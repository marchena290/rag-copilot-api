CREATE TABLE IF NOT EXISTS public.sugerencias_rag (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id integer NOT NULL,
    respuesta_generada text NOT NULL,
    fuentes_consultadas text NOT NULL,
    score_similitud_promedio double precision,
    fecha_generacion timestamp with time zone NOT NULL DEFAULT now(),
    fue_util boolean DEFAULT NULL,
    CONSTRAINT sugerencias_rag_ticket_id_fkey
        FOREIGN KEY (ticket_id)
        REFERENCES public.tickets (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS sugerencias_rag_ticket_id_idx
    ON public.sugerencias_rag (ticket_id);
